// XML/HTML 属性与文本统一转义（全仓库唯一实现）。
// 审查来源：MCHECK-REPORT F 组 P2-3、E 组 P1-3、TS-REPORT T25b ——
// 各处分散的 escapeXml 均缺少单引号转义，本实现补齐全部五个 XML 实体。
//
// ## 为什么是 5 次链式 replace，而不是「单次字符类 + 查表」
//
// 我实测过后者并**回退了**：它在三种输入形态下都更慢（0.51x ~ 0.74x）。
// 原因是 V8 对 `replace(/单个字面量/g, "替换字符串")` 有高度优化 —— 内部用
// 类似 memchr 的单字符搜索 + 直接拼接；而「单次字符类 + 替换回调」每个匹配都要
// 调一次 JS 函数，回调开销吃掉了省下的 4 次扫描收益。
//
// 实测数据（600 次 × 7 轮取中位数，Node 24）：
//   无元字符   链式 1.4ms(1.00x)  单次 2.8ms(0.51x)
//   含元字符   链式 32.4ms(1.00x) 单次 43.8ms(0.74x)
//   混合       链式 36.1ms(1.00x) 单次 55.3ms(0.65x)
//
// 「先 test 再 replace」的第三方案（无元字符时直接返回原引用）实测同样更慢
// （0.55x / 0.69x / 0.74x）—— 那次 `test` 本身也是一次全文扫描。
//
// **别再改成单次查表版**：那条路看起来更"聪明"，实测是退化。
// 回归测试见 shared/xmlEscapePerf.test.mjs（等价性 + 性能守卫）。
//
// 链式的**正确性**依据（易被想当然地误判，见该测试文件的说明）：
// 后续规则会作用在前次规则的**结果**上，而映射值 `&amp;` 本身含键 `&` ——
// 但后续规则的键（`<` `>` `"` `'`）与前面规则的输出不重叠，故不会二次转义。

/**
 * 转义 XML/HTML 五个保留字符。
 * 属性无论用单引号还是双引号包裹均安全。
 */
export function escapeXmlFull(value) {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}
