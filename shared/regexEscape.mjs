// 正则元字符转义（跨端共享单源）。
//
// 此前 `src/model.ts`、`src/svgUtils.ts`、`server/config.mjs` **各有一份**完全相同的
// 实现（`/[.*+?^${}()|[\]\\]/g`），只有 svgUtils 那份多带了个 `u` 标志。三份的转义
// 字符集一致，`u` 对这些 ASCII 元字符也无行为差异（都按单码点匹配），所以**没有 bug**
// —— 合并的收益是消除重复：改一处漏两处的风险，以及「三份实现慢慢漂移」的隐患。
//
// 选**不带 `u` 标志**的版本与原多数派一致（3 份里 2 份不带），行为与它们逐字节相同；
// `u` 标志对纯 ASCII 字符类没有收益，反而在个别旧环境上对转义组合更严格。
//
// 转义集刻意**不补 `-`**：这三个调用方都把结果用在字符类 `[...]` 内部或量词上下文，
// `-` 在那两处的转义会改变语义。改动前请先确认调用点。
//
// 同目录的 `xmlEscape.mjs` 是另一类共享（XML 实体转义），两者不要混用。
/** 把字符串里的正则元字符转义，使其可安全嵌入正则模式。 */
export function escapeRegExp(value) {
  return String(value ?? "").replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}
